FROM archived_moment_seed seed
JOIN moment target ON target.created_at = seed.created_at
JOIN archived_image_number image_number ON image_number.number_value < seed.image_count
LEFT JOIN moment_image existing
  ON existing.moment_id = target.id
 AND existing.sort = image_number.number_value
WHERE existing.id IS NULL;

