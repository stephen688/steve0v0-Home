INSERT INTO moment (content, media_type, location, created_at, updated_at)
SELECT seed.content, 'image', seed.location, seed.created_at, seed.created_at
FROM archived_moment_seed seed
WHERE NOT EXISTS (
    SELECT 1 FROM moment existing WHERE existing.created_at = seed.created_at
);

UPDATE moment target
JOIN archived_moment_seed seed ON seed.created_at = target.created_at
SET target.content = seed.content,
    target.media_type = 'image',
    target.location = seed.location;

